/**
 * @ClassName DbRunMetricsStore
 * @Description The database-backed {@link RunMetricsStore} (PostgreSQL in
 *              production, H2 in tests): one append-only row per executed or
 *              failed stage in the {@code obs_run_metrics} table, mirroring
 *              the {@code cp_*} control-plane schema style (idempotent
 *              portable DDL, {@code TIMESTAMP WITH TIME ZONE}). Rows are
 *              written by the observability actor before the timeline fold
 *              and SSE fan-out, so with PostgreSQL's write-ahead logging the
 *              per-scenario LM history (durations, retries, token
 *              consumption) survives service restarts. Aggregation groups by
 *              scenario, stage, agent and model over a time window — the
 *              shape behind the per-scenario metrics API.
 * @Author OliverGong
 * @Date Nov 1, 2026
 * @Version 1.0
 */
package com.oli.orchestrator_demo.observability.infra;
import com.oli.orchestrator_demo.observability.RunMetricsStore;

import java.sql.Timestamp;
import java.time.Instant;
import java.util.List;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.jdbc.core.simple.JdbcClient;

public class DbRunMetricsStore implements RunMetricsStore {

  private static final Logger log = LoggerFactory.getLogger(DbRunMetricsStore.class);

  /** Portable (PostgreSQL + H2) idempotent schema. */
  private static final String[] SCHEMA = {
      """
      CREATE TABLE IF NOT EXISTS obs_run_metrics (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        run_id VARCHAR(64) NOT NULL,
        scenario_id VARCHAR(64),
        stage VARCHAR(128) NOT NULL,
        agent VARCHAR(64) NOT NULL,
        model VARCHAR(128),
        wave_index INT,
        attempt INT,
        outcome VARCHAR(16) NOT NULL,
        duration_ms BIGINT,
        prompt_tokens BIGINT,
        completion_tokens BIGINT,
        total_tokens BIGINT,
        created_at TIMESTAMP WITH TIME ZONE NOT NULL
      )""",
      "CREATE INDEX IF NOT EXISTS obs_run_metrics_created_idx ON obs_run_metrics (created_at)",
      "CREATE INDEX IF NOT EXISTS obs_run_metrics_scenario_idx ON obs_run_metrics (scenario_id)"
  };

  private final JdbcClient jdbc;

  public DbRunMetricsStore(JdbcClient jdbc) {
    this.jdbc = jdbc;
  }

  /** Creates the schema idempotently. */
  public void initialize() {
    for (String ddl : SCHEMA) {
      jdbc.sql(ddl).update();
    }
    log.info("Run metrics database: durable stage metrics enabled (obs_run_metrics)");
  }

  @Override
  public void record(RunStageMetrics row) {
    jdbc.sql("""
        INSERT INTO obs_run_metrics (run_id, scenario_id, stage, agent, model, wave_index, attempt,
            outcome, duration_ms, prompt_tokens, completion_tokens, total_tokens, created_at)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""")
        .param(row.runId()).param(row.scenarioId()).param(row.stage()).param(row.agent())
        .param(row.model()).param(row.waveIndex()).param(row.attempt()).param(row.outcome())
        .param(row.durationMs()).param(row.promptTokens()).param(row.completionTokens())
        .param(row.totalTokens()).param(Timestamp.from(row.createdAt()))
        .update();
  }

  @Override
  public List<StageMetricsSummary> aggregate(Instant since, String scenarioId) {
    return jdbc.sql("""
        SELECT scenario_id, stage, agent, model, COUNT(*) AS stage_count,
            SUM(CASE WHEN outcome = 'STAGE_FAILED' THEN 1 ELSE 0 END) AS failed_count,
            COALESCE(SUM(attempt), 0) AS retries,
            AVG(duration_ms) AS avg_duration, MAX(duration_ms) AS max_duration,
            COALESCE(SUM(prompt_tokens), 0) AS prompt_tokens,
            COALESCE(SUM(completion_tokens), 0) AS completion_tokens,
            COALESCE(SUM(total_tokens), 0) AS total_tokens,
            MAX(created_at) AS last_run_at
        FROM obs_run_metrics
        WHERE created_at >= ? AND (? IS NULL OR scenario_id = ?)
        GROUP BY scenario_id, stage, agent, model
        ORDER BY scenario_id, stage""")
        .param(Timestamp.from(since)).param(scenarioId).param(scenarioId)
        .query((rs, n) -> new StageMetricsSummary(
            rs.getString("scenario_id"),
            rs.getString("stage"),
            rs.getString("agent"),
            rs.getString("model"),
            rs.getLong("stage_count"),
            rs.getLong("failed_count"),
            rs.getLong("retries"),
            rs.getObject("avg_duration") == null ? null : rs.getDouble("avg_duration"),
            rs.getObject("max_duration") == null ? null : rs.getLong("max_duration"),
            rs.getLong("prompt_tokens"),
            rs.getLong("completion_tokens"),
            rs.getLong("total_tokens"),
            rs.getTimestamp("last_run_at").toInstant()))
        .list();
  }

  @Override
  public List<RunStageMetrics> byRun(String runId) {
    return jdbc.sql("""
        SELECT run_id, scenario_id, stage, agent, model, wave_index, attempt, outcome,
            duration_ms, prompt_tokens, completion_tokens, total_tokens, created_at
        FROM obs_run_metrics WHERE run_id = ? ORDER BY created_at, id""")
        .param(runId)
        .query((rs, n) -> new RunStageMetrics(
            rs.getString("run_id"), rs.getString("scenario_id"), rs.getString("stage"),
            rs.getString("agent"), rs.getString("model"),
            (Integer) rs.getObject("wave_index"), (Integer) rs.getObject("attempt"),
            rs.getString("outcome"), (Long) rs.getObject("duration_ms"),
            (Long) rs.getObject("prompt_tokens"), (Long) rs.getObject("completion_tokens"),
            (Long) rs.getObject("total_tokens"), rs.getTimestamp("created_at").toInstant()))
        .list();
  }

  @Override
  public String name() {
    return "database";
  }
}
