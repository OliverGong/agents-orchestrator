/**
 * @ClassName DbReleaseStore
 * @Description The database-backed {@link ReleaseStore} (PostgreSQL in
 *              production, H2 in tests): one append-only {@code rl_release}
 *              table carrying the release metadata, the package hash and the
 *              full package JSON — the same portable DDL style as the other
 *              planes.
 * @Author OliverGong
 * @Date Nov 1, 2026
 * @Version 1.0
 */
package com.oli.orchestrator_demo.governance.release.infra;
import com.oli.orchestrator_demo.governance.release.ReleaseRecord;
import com.oli.orchestrator_demo.governance.release.ReleaseStore;

import java.sql.Timestamp;
import java.util.List;
import java.util.Optional;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.transaction.annotation.Transactional;

public class DbReleaseStore implements ReleaseStore {

  private static final Logger log = LoggerFactory.getLogger(DbReleaseStore.class);

  /** Portable (PostgreSQL + H2) idempotent schema. */
  private static final String[] SCHEMA = {
      """
      CREATE TABLE IF NOT EXISTS rl_release (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        scenario_id VARCHAR(64) NOT NULL,
        portal_id VARCHAR(64),
        release_version VARCHAR(64),
        changelog TEXT,
        artifact_type VARCHAR(32),
        published_at TIMESTAMP WITH TIME ZONE NOT NULL,
        package_hash VARCHAR(64) NOT NULL,
        package_json TEXT NOT NULL
      )""",
      "CREATE INDEX IF NOT EXISTS idx_rl_release_scenario ON rl_release (scenario_id, published_at)"
  };

  private final JdbcClient jdbc;

  public DbReleaseStore(JdbcClient jdbc) {
    this.jdbc = jdbc;
  }

  /** Creates the schema idempotently. */
  public void initialize() {
    for (String ddl : SCHEMA) {
      jdbc.sql(ddl).update();
    }
    log.info("Release registry: database backend enabled (rl_release table)");
  }

  @Override
  @Transactional
  public ReleaseRecord append(ReleaseRecord record) {
    jdbc.sql("""
        INSERT INTO rl_release (scenario_id, portal_id, release_version, changelog,
            artifact_type, published_at, package_hash, package_json)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?)""")
        .param(record.scenarioId()).param(record.portalId()).param(record.releaseVersion())
        .param(record.changelog()).param(record.artifactType())
        .param(Timestamp.from(record.publishedAt())).param(record.packageHash())
        .param(record.packageJson())
        .update();
    // Single-writer registry: MAX(id) is the row we just inserted.
    long id = jdbc.sql("SELECT MAX(id) FROM rl_release").query(Long.class).single();
    return new ReleaseRecord(id, record.scenarioId(), record.portalId(), record.releaseVersion(),
        record.changelog(), record.artifactType(), record.publishedAt(), record.packageHash(),
        record.packageJson());
  }

  private static final String SELECT = """
      SELECT id, scenario_id, portal_id, release_version, changelog, artifact_type,
             published_at, package_hash, package_json FROM rl_release""";

  @Override
  public List<ReleaseRecord> list(String scenarioId) {
    if (scenarioId == null) {
      return jdbc.sql(SELECT + " ORDER BY id DESC")
          .query((rs, n) -> mapRow(rs.getLong("id"), rs))
          .list();
    }
    return jdbc.sql(SELECT + " WHERE scenario_id = ? ORDER BY id DESC")
        .param(scenarioId)
        .query((rs, n) -> mapRow(rs.getLong("id"), rs))
        .list();
  }

  @Override
  public Optional<ReleaseRecord> get(long id) {
    return jdbc.sql(SELECT + " WHERE id = ?")
        .param(id)
        .query((rs, n) -> mapRow(rs.getLong("id"), rs))
        .optional();
  }

  private ReleaseRecord mapRow(long id, java.sql.ResultSet rs) throws java.sql.SQLException {
    return new ReleaseRecord(id, rs.getString("scenario_id"), rs.getString("portal_id"),
        rs.getString("release_version"), rs.getString("changelog"), rs.getString("artifact_type"),
        rs.getTimestamp("published_at").toInstant(), rs.getString("package_hash"),
        rs.getString("package_json"));
  }

  @Override
  public String name() {
    return "database";
  }
}
