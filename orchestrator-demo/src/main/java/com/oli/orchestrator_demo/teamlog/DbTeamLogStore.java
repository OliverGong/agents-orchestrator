/**
 * @ClassName DbTeamLogStore
 * @Description The database-backed {@link TeamLogStore} (PostgreSQL in
 *              production, H2 in tests): one append-only {@code team_log}
 *              table with an identity id and timestamp/category indices —
 *              the same portable DDL style as the {@code cp_*} / {@code mp_*}
 *              / {@code obs_*} planes. Search facets are translated into a
 *              dynamic WHERE clause, newest first.
 * @Author OliverGong
 * @Date Nov 1, 2026
 * @Version 1.0
 */
package com.oli.orchestrator_demo.teamlog;

import java.sql.Timestamp;
import java.time.Instant;
import java.util.List;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.jdbc.core.namedparam.MapSqlParameterSource;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.transaction.annotation.Transactional;

public class DbTeamLogStore implements TeamLogStore {

  private static final Logger log = LoggerFactory.getLogger(DbTeamLogStore.class);

  /** Portable (PostgreSQL + H2) idempotent schema. */
  private static final String[] SCHEMA = {
      """
      CREATE TABLE IF NOT EXISTS team_log (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ts TIMESTAMP WITH TIME ZONE NOT NULL,
        category VARCHAR(16) NOT NULL,
        level VARCHAR(8) NOT NULL,
        source VARCHAR(32) NOT NULL,
        run_id VARCHAR(64),
        scenario_id VARCHAR(64),
        action VARCHAR(64) NOT NULL,
        message TEXT NOT NULL,
        detail TEXT
      )""",
      "CREATE INDEX IF NOT EXISTS idx_team_log_ts ON team_log (ts)",
      "CREATE INDEX IF NOT EXISTS idx_team_log_cat ON team_log (category, level)"
  };

  private final JdbcClient jdbc;

  public DbTeamLogStore(JdbcClient jdbc) {
    this.jdbc = jdbc;
  }

  /** Creates the schema idempotently. */
  public void initialize() {
    for (String ddl : SCHEMA) {
      jdbc.sql(ddl).update();
    }
    log.info("Team log: database backend enabled (team_log table)");
  }

  @Override
  @Transactional
  public void append(TeamLogEntry entry) {
    jdbc.sql("""
        INSERT INTO team_log (ts, category, level, source, run_id, scenario_id, action, message, detail)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)""")
        .param(Timestamp.from(entry.ts())).param(entry.category()).param(entry.level())
        .param(entry.source()).param(entry.runId()).param(entry.scenarioId())
        .param(entry.action()).param(entry.message()).param(entry.detail())
        .update();
  }

  @Override
  public List<TeamLogEntry> search(TeamLogQuery query) {
    StringBuilder where = new StringBuilder(" WHERE 1=1");
    MapSqlParameterSource params = new MapSqlParameterSource();
    if (query.since() != null) {
      where.append(" AND ts >= :since");
      params.addValue("since", Timestamp.from(query.since()));
    }
    if (query.category() != null) {
      where.append(" AND UPPER(category) = :category");
      params.addValue("category", query.category().toUpperCase());
    }
    if (query.level() != null) {
      where.append(" AND UPPER(level) = :level");
      params.addValue("level", query.level().toUpperCase());
    }
    if (query.runId() != null) {
      where.append(" AND run_id = :runId");
      params.addValue("runId", query.runId());
    }
    if (query.scenarioId() != null) {
      where.append(" AND scenario_id = :scenarioId");
      params.addValue("scenarioId", query.scenarioId());
    }
    if (query.text() != null && !query.text().isBlank()) {
      where.append(" AND (LOWER(message) LIKE :text OR LOWER(action) LIKE :text "
          + "OR LOWER(source) LIKE :text OR LOWER(detail) LIKE :text)");
      params.addValue("text", "%" + query.text().toLowerCase() + "%");
    }
    // The limit is a clamped int (never user-controlled raw), so it can go
    // into the SQL verbatim — H2 rejects a bind parameter in LIMIT.
    int limit = Math.max(1, query.limit());
    where.append(" ORDER BY ts DESC, id DESC LIMIT ").append(limit);

    return jdbc.sql("SELECT id, ts, category, level, source, run_id, scenario_id, action, message, detail "
        + "FROM team_log" + where)
        .paramSource(params)
        .query((rs, n) -> new TeamLogEntry(rs.getLong("id"), rs.getTimestamp("ts").toInstant(),
            rs.getString("category"), rs.getString("level"), rs.getString("source"),
            rs.getString("run_id"), rs.getString("scenario_id"), rs.getString("action"),
            rs.getString("message"), rs.getString("detail")))
        .list();
  }

  @Override
  public String name() {
    return "database";
  }
}
